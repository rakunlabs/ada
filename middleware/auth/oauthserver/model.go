package oauthserver

import (
	"context"
	"encoding/json"
	"errors"
	"slices"
	"time"

	"github.com/rakunlabs/ada/middleware/auth/identity"
)

var (
	// ErrNotFound is returned by a Store when a record does not exist. A
	// Store must return it (or wrap it) for unknown clients, codes, tokens
	// and consents; any other error is treated as an outage.
	ErrNotFound = errors.New("oauthserver: not found")

	// ErrConflict is returned by Store.RotateToken when the refresh token was
	// rotated by somebody else first.
	ErrConflict = errors.New("oauthserver: conflict")

	// ErrAccessDenied can be returned by Hooks.Identity to refuse a token
	// whose user may no longer sign in (disabled, deleted). It becomes
	// invalid_grant at the token endpoint and 401 on a protected route.
	ErrAccessDenied = errors.New("oauthserver: access denied")
)

// Token endpoint client authentication methods (RFC 7591 §2).
const (
	AuthMethodNone   = "none"
	AuthMethodBasic  = "client_secret_basic"
	AuthMethodPost   = "client_secret_post"
	GrantCode        = "authorization_code"
	GrantRefresh     = "refresh_token"
	ResponseTypeCode = "code"
)

// Client is a registered OAuth client.
type Client struct {
	// ID is the client_id, generated by the server.
	ID string
	// Name is the human-readable client_name shown on the consent page.
	Name string
	// RedirectURIs are the registered redirect URIs. On the loopback
	// interface the port may differ at authorization time (RFC 8252 §7.3).
	RedirectURIs []string
	// GrantTypes the client may use. Empty means authorization_code and
	// refresh_token.
	GrantTypes []string
	// TokenEndpointAuthMethod is none (public client, the default for
	// dynamic registration), client_secret_basic or client_secret_post.
	TokenEndpointAuthMethod string
	// SecretHash is the SHA-256 hex digest of the client secret, empty for
	// public clients. The secret itself is never stored.
	SecretHash string
	// CreatedAt is when the client was registered.
	CreatedAt time.Time
}

// Public reports whether the client has no secret.
func (c *Client) Public() bool {
	return c.TokenEndpointAuthMethod == "" || c.TokenEndpointAuthMethod == AuthMethodNone
}

// AllowsGrant reports whether the client may use the grant type.
func (c *Client) AllowsGrant(grant string) bool {
	if len(c.GrantTypes) == 0 {
		return grant == GrantCode || grant == GrantRefresh
	}

	return slices.Contains(c.GrantTypes, grant)
}

// Code is an authorization code waiting to be exchanged.
type Code struct {
	// Hash is the SHA-256 hex digest of the code. The code itself is never
	// stored.
	Hash          string
	ClientID      string
	Identity      *identity.Identity
	RedirectURI   string
	CodeChallenge string
	Scopes        []string
	Resource      string
	Extra         map[string]any
	ExpiresAt     time.Time
}

// Token is an issued access token, with its refresh token when it has one.
//
// Tokens are opaque random strings; only their hashes are stored, so a leaked
// database does not leak usable credentials.
type Token struct {
	// ID identifies the token for listing and revocation.
	ID string
	// ClientID is the OAuth client the token was issued to. Empty for
	// personal access tokens made with Server.IssueToken.
	ClientID string
	// Name is a label: the client name, or the name given to a personal
	// token.
	Name string
	// Identity is the user the token acts as, captured at authorization.
	// Hooks.Identity can refresh it on every use.
	Identity *identity.Identity
	// Scopes granted to the token.
	Scopes []string
	// Resource is the RFC 8707 resource the token was issued for. Empty
	// when the client did not name one.
	Resource string
	// Extra is application data attached by Hooks.Authorize (for example
	// the one database connection a token is limited to). Keep values
	// JSON-friendly: a SQL store will round-trip them through JSON.
	Extra map[string]any

	AccessHash      string
	AccessExpiresAt time.Time // zero means it never expires
	// RefreshHash is empty when the token has no refresh token.
	RefreshHash      string
	RefreshExpiresAt time.Time // zero means it never expires
	// PreviousRefreshHash is the refresh token this one replaced. Seeing it
	// again means a rotated-out refresh token is being replayed — stolen,
	// most likely — and the whole grant is revoked (OAuth 2.1 §4.3.1).
	PreviousRefreshHash string
	// RotatedAt is when the refresh token was last rotated. A replay of the
	// previous refresh token within a short grace period after it is a
	// client retrying a request that raced, not a theft, and is only
	// refused.
	RotatedAt time.Time
	// GrantedScopes are the scopes the user approved. A refresh may ask for
	// fewer (Scopes), and a later refresh may ask for them back.
	GrantedScopes []string
	CreatedAt     time.Time
}

// Subject returns the subject of the token's identity.
func (t *Token) Subject() string {
	if t == nil || t.Identity == nil {
		return ""
	}

	return t.Identity.Subject
}

// Consent is a remembered approval: the user will not be asked again for the
// same client while the request stays within it.
type Consent struct {
	Subject  string
	ClientID string
	Scopes   []string
	Resource string
	// ExtraHash fingerprints the AuthorizeRequest.Extra the user approved.
	// A request whose hook attaches something else (another connection,
	// say) is asked again.
	ExtraHash string
	CreatedAt time.Time
}

// ExtraHash returns the fingerprint stored in Consent.ExtraHash.
func ExtraHash(extra map[string]any) string {
	if len(extra) == 0 {
		return ""
	}

	b, err := json.Marshal(extra) // map keys are sorted
	if err != nil {
		return "unhashable"
	}

	return HashSecret(string(b))
}

// Store persists clients, codes and tokens.
//
// IDs are generated by the server before a record reaches the store. Lookups
// of unknown records return ErrNotFound. See MemoryStore for a reference
// implementation and the documentation for a SQL schema.
type Store interface {
	CreateClient(ctx context.Context, c *Client) error
	GetClient(ctx context.Context, id string) (*Client, error)

	SaveCode(ctx context.Context, c *Code) error
	// TakeCode returns the code and deletes it in one step, so a code can be
	// exchanged only once even across replicas.
	TakeCode(ctx context.Context, hash string) (*Code, error)

	SaveToken(ctx context.Context, t *Token) error
	TokenByAccess(ctx context.Context, accessHash string) (*Token, error)
	// TokenByRefresh finds the token whose current RefreshHash or
	// PreviousRefreshHash is refreshHash.
	TokenByRefresh(ctx context.Context, refreshHash string) (*Token, error)
	// RotateToken replaces the token with ID t.ID only if its current
	// refresh hash is still oldRefreshHash; otherwise it returns
	// ErrConflict. This is a compare-and-swap: of two refreshes racing with
	// the same refresh token exactly one wins.
	RotateToken(ctx context.Context, oldRefreshHash string, t *Token) error
	DeleteToken(ctx context.Context, id string) error
}

// ClientFinder is an optional Store capability used to reuse a client that
// registers again with the same name and redirect URIs, so one application
// (Claude Code, Cursor, …) shows up once instead of once per sign-in.
type ClientFinder interface {
	ClientsByName(ctx context.Context, name string) ([]*Client, error)
}

// ConsentStore is an optional Store capability that enables "remember this
// approval" on the consent page.
type ConsentStore interface {
	SaveConsent(ctx context.Context, c *Consent) error
	GetConsent(ctx context.Context, subject, clientID string) (*Consent, error)
	DeleteConsent(ctx context.Context, subject, clientID string) error
}
