// Package users is a local user directory for middleware/auth: accounts with
// hashed passwords, roles, role-based permissions, an admin API to manage
// them and a self-service API for the signed-in user.
//
// It plugs into the existing pieces rather than replacing them:
//
//   - Verifier and Registrar feed strategy/local, so the built-in login page
//     signs users in (and signs them up, when enabled)
//   - Fresh re-reads the user on every request, so disabling or demoting
//     someone takes effect at once
//   - Permission and RequirePermission check permissions derived from roles
//   - IdentityHook keeps oauthserver tokens in step with the user
//
// Most applications use it through package kit, which wires all of this in
// one call.
package users

import (
	"context"
	"errors"
	"slices"
	"strings"
	"time"
)

var (
	// ErrNotFound is returned by a Store for an unknown user.
	ErrNotFound = errors.New("users: not found")
	// ErrExists is returned by a Store when the username is taken.
	ErrExists = errors.New("users: username already exists")
	// ErrInvalid wraps validation failures; the message is safe to show.
	ErrInvalid = errors.New("users: invalid")
	// ErrLastAdmin refuses a change that would leave no enabled user able
	// to administer users.
	ErrLastAdmin = errors.New("users: cannot remove the last administrator")
)

// User is an account.
type User struct {
	// ID is the stable identifier and the identity subject. Generated by
	// the service; never reused.
	ID string `json:"id"`
	// Username is the login name, unique, compared case-insensitively.
	Username string `json:"username"`
	Name     string `json:"name,omitempty"`
	Email    string `json:"email,omitempty"`
	// PasswordHash is the encoded hash from a password.Hasher. Empty means
	// the user cannot sign in with a password (e.g. SSO-only).
	PasswordHash string   `json:"-"`
	Roles        []string `json:"roles"`
	Disabled     bool     `json:"disabled,omitempty"`
	// Attributes carries application data (department, avatar, …). Keep it
	// JSON-friendly.
	Attributes map[string]any `json:"attributes,omitempty"`
	CreatedAt  time.Time      `json:"created_at"`
	UpdatedAt  time.Time      `json:"updated_at"`
}

// HasPassword reports whether the user can sign in with a password.
func (u *User) HasPassword() bool { return u.PasswordHash != "" }

// Role names a set of permissions.
type Role struct {
	Name        string `cfg:"name" json:"name"`
	Description string `cfg:"description" json:"description,omitempty"`
	// Permissions are strings such as "users:write" or "reports:read".
	// "*" grants everything; a trailing "*" grants a prefix ("reports:*").
	Permissions []string `cfg:"permissions" json:"permissions"`
}

// Built-in role names.
const (
	RoleAdmin = "admin"
	RoleUser  = "user"
)

// Built-in permissions, used by the admin API.
const (
	PermUsersRead  = "users:read"
	PermUsersWrite = "users:write"
	PermAll        = "*"
)

// DefaultRoles are used when Config.Roles is empty: admin may do anything,
// user may do nothing beyond being signed in.
func DefaultRoles() []Role {
	return []Role{
		{Name: RoleAdmin, Description: "Full access", Permissions: []string{PermAll}},
		{Name: RoleUser, Description: "Signed-in user"},
	}
}

// Grants reports whether a permission pattern grants perm.
func Grants(pattern, perm string) bool {
	if pattern == "" || perm == "" {
		return false
	}
	if pattern == PermAll || pattern == perm {
		return true
	}

	prefix, ok := strings.CutSuffix(pattern, "*")

	return ok && strings.HasPrefix(perm, prefix)
}

// Store persists users. Lookups of unknown users return ErrNotFound;
// CreateUser and UpdateUser return ErrExists for a taken username.
type Store interface {
	CreateUser(ctx context.Context, u *User) error
	GetUser(ctx context.Context, id string) (*User, error)
	// GetUserByUsername must match case-insensitively.
	GetUserByUsername(ctx context.Context, username string) (*User, error)
	ListUsers(ctx context.Context) ([]*User, error)
	// UpdateUser replaces every field of the user with ID u.ID.
	UpdateUser(ctx context.Context, u *User) error
	DeleteUser(ctx context.Context, id string) error
	CountUsers(ctx context.Context) (int, error)
}

func cloneUser(u *User) *User {
	if u == nil {
		return nil
	}

	cp := *u
	cp.Roles = slices.Clone(u.Roles)
	if u.Attributes != nil {
		cp.Attributes = make(map[string]any, len(u.Attributes))
		for k, v := range u.Attributes {
			cp.Attributes[k] = v
		}
	}

	return &cp
}
